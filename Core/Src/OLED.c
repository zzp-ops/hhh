/* ===========================================================================
 * OLED.c —— SSD1306 128x64 软件 I2C 驱动
 *
 * 移植自 oled 工程（HSI 8MHz / PB8-PB9），移植到 hh 工程后的三处改动：
 *
 *   ① 延时时基 —— 原工程按 8MHz 写死 4 次空循环；本工程 72MHz，
 *      空循环缩短 9 倍会把 SCL 推到 2MHz 以上（SSD1306 上限 400kHz）。
 *      现改为按 SystemCoreClock 自动换算，8MHz / 72MHz 都能落在 ~330kHz。
 *
 *   ② 引脚模式 —— hh 的 MX_GPIO_Init() 把 PB8/PB9 配成了推挽输出
 *      （GPIO_MODE_OUTPUT_PP）。I2C 必须开漏，否则模块的 5V 上拉会和
 *      MCU 的推挽高电平对顶。OLED_Init() 里重新配成 OUTPUT_OD 覆盖。
 *
 *   ③ 批量写 —— 原工程每个数据字节都单独发一次 起始+地址+控制+数据+停止，
 *      全屏 1024 字节要发 1024 帧。这里加了 OLED_WriteDataBlock()，
 *      控制字节 0x40 只发一次，后面连续发数据，全屏刷新快 3 倍多。
 *      对「OLED 刷新不能拖慢 5ms 控制周期」这条要求很关键。
 * =========================================================================== */

