#ifndef __GETDATA_H
#define __GETDATA_H

#include "main.h"

/* ===========================================================================
 * 测距数据获取层
 *
 * 只做两件事：
 *   1. 把 VL53L0X 初始化一次，并对外报告「模块启动状态」
 *   2. 非阻塞地取距离，单位 mm
 *
 * 回波强度、环境光、中值滤波、刻度换算都不在这里，这一层只给原始 mm。
 *
 * 用法（主循环里每周期调一次）：
 *
 *     GetData_Init(&hi2c2);
 *
 *     while (1) {
 *         int32_t mm = GetData_ReadDistanceMm();
 *         if (mm >= 0) {
 *             // 有效距离，单位 mm
 *         }
 *     }
 * =========================================================================== */

/* ---------------------------------------------------------------------------
 * 模块启动状态
 * ------------------------------------------------------------------------- */
typedef enum {
    GETDATA_STATE_UNINIT = 0,   /* 还没调用 GetData_Init()                          */
    GETDATA_STATE_OK     = 1,   /* 初始化成功，正常工作                              */
    GETDATA_STATE_NODEV  = 2,   /* I2C 无应答 / 型号不是 0xEE —— 查接线、供电、上拉  */
    GETDATA_STATE_FAIL   = 3    /* 芯片在线但 ST API 初始化失败 —— 查第几步           */
} GetData_State;

/* ---------------------------------------------------------------------------
 * GetData_ReadDistanceMm() 的负返回值
 * ------------------------------------------------------------------------- */
#define GETDATA_NO_DATA     (-1)    /* 从头到尾还没测出过一次有效距离          */
#define GETDATA_INVALID     (-2)    /* 最近一次测量无效（没目标/信号弱/超时）  */
#define GETDATA_UNINIT      (-3)    /* 模块没初始化好，不能读                  */

/* ---------------------------------------------------------------------------
 * 初始化
 * ------------------------------------------------------------------------- */

/**
  * @brief  初始化测距模块
  * @param  hi2c 传感器所在的 I2C 句柄，本工程传 &hi2c2
  * @retval 模块状态。GETDATA_STATE_OK 表示可以正常读数
  *
  * @note   这一步阻塞约 1 秒（参考 SPAD 校准），只在上电调用一次。
  */
GetData_State GetData_Init(I2C_HandleTypeDef *hi2c);

/**
  * @brief  取模块当前状态
  */
GetData_State GetData_GetState(void);

/**
  * @brief  模块是否就绪
  * @retval 1 就绪，0 未就绪
  */
uint8_t GetData_IsReady(void);

/**
  * @brief  初始化失败时，查卡在第几步（透传 VL53L0X_GetInitError()）
  * @retval 0 成功；2 读型号无应答；3 型号不对；4~7 API 内部失败
  */
uint8_t GetData_GetInitStep(void);

/* ---------------------------------------------------------------------------
 * 读距离
 * ------------------------------------------------------------------------- */

/**
  * @brief  非阻塞读距离，单位 mm
  * @retval >= 0            最新一次有效距离，单位 mm
  * @retval GETDATA_NO_DATA  (-1) 还没测出过一次
  * @retval GETDATA_INVALID  (-2) 最近一次测量无效
  * @retval GETDATA_UNINIT   (-3) 模块没就绪
  *
  * @note   内部就是 VL53L0X_Service()，永远立即返回。
  *         一次完整测量约 33ms，所以连续调用时大约每 33ms 才跳一次新值，
  *         中间那些调用直接返回上一次的结果。
  *
  *         典型调用节奏：主循环里多快都行，不用限速。
  */
int32_t GetData_ReadDistanceMm(void);

#endif /* __GETDATA_H */
