#ifndef __VL53L0X_H
#define __VL53L0X_H

#include "main.h"
#include "vl53l0x_api.h"

/* ===========================================================================
 * VL53L0X 激光测距驱动 —— 工程封装层（非阻塞版）
 *
 * 底下跑的是 ST 官方 API v1.0.4（D:\download\STSW-IMG005\VL53L0X_1.0.4，
 * 已原样搬进 Core/Inc/vl53l0x 和 Core/Src/vl53l0x）。
 *
 * ---------------------------------------------------------------------------
 * 为什么不用 VL53L0X_PerformSingleRangingMeasurement()
 * ---------------------------------------------------------------------------
 * 那个函数内部是「启动测量 → 死等中断标志 → 读结果」，一次要等满
 * timing budget（默认 33ms）。放进 200Hz 控制环里等于每个周期卡 33ms，
 * 绝对不能这么写。
 *
 * 本层把它拆成三步，每步都不阻塞：
 *
 *     VL53L0X_StartSingleShot()   启动一次测量，写完寄存器立刻返回
 *     VL53L0X_PollMeasDone()      问一句「好了没」，没到时间连 I2C 都不碰
 *     VL53L0X_GetDistanceMm()     确认好了再把结果读出来
 *
 * 或者直接用一个 VL53L0X_Service() 把三步串起来，每周期调它一次即可。
 *
 * ---------------------------------------------------------------------------
 * 接线（对应 hh.ioc 现有配置，硬件 I2C）
 * ---------------------------------------------------------------------------
 *   VL53L0X VCC  --- 3V3
 *   VL53L0X GND  --- GND
 *   VL53L0X SCL  --- PB10  (I2C2_SCL，复用开漏)
 *   VL53L0X SDA  --- PB11  (I2C2_SDA，复用开漏)
 *   VL53L0X XSHUT--- PA12  (推挽输出，本层负责拉高拉低)
 *   VL53L0X GPIO1--- 不接，完成与否靠轮询 RESULT_INTERRUPT_STATUS
 *
 * PB8/PB9 是 OLED 的软件 I2C，和这里不冲突。
 *
 * ---------------------------------------------------------------------------
 * 用法 A：三步走（最灵活）
 * ---------------------------------------------------------------------------
 *   在 200Hz 的控制周期里：
 *
 *     switch (VL53L0X_PollMeasDone()) {
 *     case 1:                                   // 本次测完了
 *         mm = VL53L0X_GetDistanceMm();
 *         VL53L0X_StartSingleShot();            // 立刻开始下一次
 *         break;
 *     case 0:                                   // 还在测，下周期再看
 *         break;
 *     default:                                  // 出错，重开
 *         VL53L0X_StartSingleShot();
 *         break;
 *     }
 *
 * ---------------------------------------------------------------------------
 * 用法 B：一行流（推荐起步）
 * ---------------------------------------------------------------------------
 *     int32_t mm;
 *     if (VL53L0X_Service(&mm) == 1) {
 *         // 拿到一个新样本，mm 单位毫米；mm < 0 说明这次测量无效
 *     }
 *
 *   VL53L0X_Service() 永远立即返回，内部自己管「启动 / 等待 / 取数 / 再启动」。
 *
 * ---------------------------------------------------------------------------
 * 时间开销
 * ---------------------------------------------------------------------------
 *   一次测距按时序分三段时间：
 *
 *     启动           ≈ 0.2ms   几笔 I2C 写 + 一小段有界轮询，无延时
 *     等待           ≈ 0       PollMeasDone() 先用 HAL_GetTick() 比对时间，
 *                              没到预算就直接返回，一次 I2C 都不发
 *     取数           ≈ 0.3ms   1 字节状态 + 12 字节结果 + 1 字节清中断
 *
 *   所以除了「到点那一次」要花约 0.5ms 做 I2C，其余周期的开销接近于零。
 *
 *   注意：读结果那 ~0.5ms 在中断里做是可以的，但请放在**低频**周期里。
 *         如果放在 200Hz（5ms）的定时器中断里，占掉 10% 的中断时间，
 *         建议改到主循环或者 100Hz 以下的任务里做。
 * =========================================================================== */

/* ---------------------------------------------------------------------------
 * 引脚与地址
 * ------------------------------------------------------------------------- */

/* XSHUT：拉低让芯片进 Hw Standby，拉高启动固件。
 * CubeMX 里 PA12 已经配成 GPIO_Output 推挽、上电初值低，正好当复位脚用。 */
#define VL53L0X_XSHUT_PORT          GPIOA
#define VL53L0X_XSHUT_PIN           GPIO_PIN_12

/* 7 位从机地址 0x29 左移一位 = 0x52，ST 例程统一用这个 8 位形式 */
#define VL53L0X_I2C_ADDR            0x52

/* 型号寄存器 0xC0 的固定值，用来判断芯片在不在 */
#define VL53L0X_MODEL_ID_REG        0xC0
#define VL53L0X_MODEL_ID_VALUE      0xEE

/* ---------------------------------------------------------------------------
 * 返回值约定
 *
 * VL53L0X_GetDistanceMm() 返回 int32_t：>= 0 是毫米数，< 0 是下面的错误码。
 * VL53L0X_Service() 返回 int8_t：1 有新数据，0 还没有，< 0 是错误码。
 * ------------------------------------------------------------------------- */
#define VL53L0X_ERR_NOT_INIT        (-5)    /* 还没调用过 VL53L0X_Init()             */
#define VL53L0X_ERR_NOT_STARTED     (-6)    /* 还没有 Start 就去取结果                */
#define VL53L0X_ERR_TIMEOUT         (-7)    /* 超时：芯片一直没报完成，已自动复位状态 */
#define VL53L0X_ERR_RANGE           (-3)    /* 测到东西但状态无效：无目标、信号太弱、
                                               超出量程等，详见 VL53L0X_GetRangeStatus() */
#define VL53L0X_ERR_API             (-2)    /* ST API 返回错误（通信层问题）           */
#define VL53L0X_ERR_NO_DEVICE       (-1)    /* 初始化时 I2C 上没应答                   */

/* 状态机取值，给 VL53L0X_GetState() 用 */
#define VL53L0X_ST_IDLE             0       /* 空闲，可以 StartSingleShot()            */
#define VL53L0X_ST_WAIT             1       /* 测量中，等 PollMeasDone() 返回 1         */

/* ---------------------------------------------------------------------------
 * 初始化
 * ------------------------------------------------------------------------- */

/**
  * @brief  上电初始化 VL53L0X
  * @param  hi2c 传感器所在的 I2C 外设句柄，本工程传 &hi2c2
  * @retval 1 成功，0 失败（和 OLED_Init() 的返回习惯保持一致）
  *
  * @note   这一步是**阻塞**的，大约 1 秒（参考 SPAD 校准占大头）。
  *         它只在上电时跑一次，放在 main() 的 USER CODE 2 里，
  *         不参与控制环，所以不影响实时性。
  *         想缩短：把 VL53L0X.c 里的 VL53L0X_RUN_REF_SPAD_MANAGEMENT
  *         改成 0，启动时间会降到 100ms 以内。
  */
uint8_t VL53L0X_Init(I2C_HandleTypeDef *hi2c);

/**
  * @brief  驱动是否已经初始化成功
  * @retval 1 已就绪，0 未就绪
  */
uint8_t VL53L0X_IsReady(void);

/**
  * @brief  取当前状态机状态
  * @retval VL53L0X_ST_IDLE 或 VL53L0X_ST_WAIT
  */
uint8_t VL53L0X_GetState(void);

/**
  * @brief  初始化失败时，查卡在第几步
  * @retval 0  成功
  *         1  参数错误（I2C 句柄传了 NULL）
  *         2  读型号寄存器 0xC0 无应答  → 查接线、供电、上拉、XSHUT
  *         3  型号值不是 0xEE           → 不是 VL53L0X，或者芯片没启动
  *         4  DataInit 失败
  *         5  StaticInit 失败           → 常见于通信中途出错
  *         6  参考校准失败
  *         7  设置测距模式失败
  */
uint8_t VL53L0X_GetInitError(void);

/**
  * @brief  初始化失败时，第几步返回的 ST API 原始错误码
  * @retval 0 成功；负数见 vl53l0x_def.h 里的 VL53L0X_ERROR_xxx
  *         （-20 = 通信接口错，-50 = 参考 SPAD 初始化失败）
  */
VL53L0X_Error VL53L0X_GetInitApiError(void);

/* ---------------------------------------------------------------------------
 * 非阻塞测距：三步走
 * ------------------------------------------------------------------------- */

/**
  * @brief  启动一次单次测距，立即返回
  * @retval 1 已启动；0 没启动（未初始化，或者上一次测量还没取走结果）
  *
  * @note   内部做的是官方 VL53L0X_StartMeasurement()：几笔寄存器写，
  *         再加一小段有界轮询等 START 位自动清零（没有 HAL_Delay）。
  *         耗时约 0.2ms。
  *
  *         芯片不会自动开始下一次，所以取完结果后要再调一次本函数。
  */
uint8_t VL53L0X_StartSingleShot(void);

/**
  * @brief  查询本次测量是否完成，立即返回
  * @retval 1   完成了，可以调 VL53L0X_GetDistanceMm() 取结果
  * @retval 0   还在测，过一会儿再来问
  * @retval < 0 错误码（VL53L0X_ERR_NOT_STARTED / _API / _TIMEOUT 等）
  *
  * @note   这个函数**不会阻塞**。它先用 HAL_GetTick() 算距离启动过去了多久，
  *         还没到 timing budget 就直接返回 0，一次 I2C 都不发；
  *         到点了才去读一字节 RESULT_INTERRUPT_STATUS（约 0.05ms）。
  *
  *         超时保护：超过「预算 + 20ms」还没完成，会判定芯片卡住，
  *         自动把状态机复位回 IDLE 并返回 VL53L0X_ERR_TIMEOUT，
  *         调用方重新 StartSingleShot() 即可恢复。
  */
int8_t VL53L0X_PollMeasDone(void);

/**
  * @brief  取本次测量结果
  * @retval >= 0  传感器到目标的距离，单位 mm
  * @retval <  0  错误码（VL53L0X_ERR_RANGE 表示测到但不可信）
  *
  * @note   必须先 PollMeasDone() 返回 1 再调用。内部会读 12 字节结果区、
  *         清中断标志、把状态机复位回 IDLE，耗时约 0.3ms。
  *         每次调用都会刷新 VL53L0X_GetRangeStatus() 和
  *         VL53L0X_GetSignalRateMcps() 的值。
  */
int32_t VL53L0X_GetDistanceMm(void);

/* ---------------------------------------------------------------------------
 * 非阻塞测距：一行流
 * ------------------------------------------------------------------------- */

/**
  * @brief  每周期调一次，内部自动「启动 → 等 → 取 → 再启动」
  * @param  distance_mm 输出，拿到新数据时写入距离（>=0）或错误码（<0）。可以传 NULL。
  * @retval 1   本次调用拿到了一个新样本
  * @retval 0   还没有新样本（测量进行中，或刚开始一次新测量）
  * @retval < 0 错误码
  *
  * @note   永远立即返回，不会阻塞任何一个周期。
  *         典型调用节奏：主循环里每 5~20ms 调一次，
  *         或者放进 100Hz 的定时器标志里在主循环处理。
  */
int8_t VL53L0X_Service(int32_t *distance_mm);

/* ---------------------------------------------------------------------------
 * 结果与诊断
 * ------------------------------------------------------------------------- */

/**
  * @brief  取最近一次测距的测距状态
  * @retval 0   本次测量有效
  *         1   信号太弱（目标太远或反射率太低）
  *         2   精度不够（sigma 超限）
  *         3   目标太小 / 信号不足
  *         4   相位一致性检查失败
  *         5   硬件故障
  *         其余见 ST 文档 dm00279088 中 RangeStatus 一节
  */
uint8_t VL53L0X_GetRangeStatus(void);

/**
  * @brief  取最近一次测距的返回信号强度
  * @retval 单位 MCPS（兆计数每秒），数值越大说明回波越强。
  *         钢管里打钢珠回波很弱，可以用它判断球是不是滚出视场了。
  */
uint16_t VL53L0X_GetSignalRateMcps(void);

/**
  * @brief  取最近一次测距的环境光强度
  * @retval 单位 MCPS。室内基本恒定（几到几十），突然飙高说明有强光干扰。
  */
uint16_t VL53L0X_GetAmbientRateMcps(void);

/* ---------------------------------------------------------------------------
 * 参数调整（这些只在初始化后调一次，不要放进控制环）
 * ------------------------------------------------------------------------- */

/**
  * @brief  设置距离偏移校正
  * @param  offset_mm 偏移量，单位 mm。测量值偏大就设负数把它拉回来。
  *
  * @note   官方推荐用 10cm 处的白色目标（88% 反射率）标定，暗环境。
  *         本工程传感器固定在水管一端、对着管内钢珠测，气隙和盖玻片
  *         都会带来固定偏移。建议装好后让钢珠停在刻度 0 处实测一次，
  *         把「读数 − 真实距离」填进去。
  */
void VL53L0X_SetOffsetMm(int16_t offset_mm);

/**
  * @brief  读回当前距离偏移校正，单位 mm
  */
int16_t VL53L0X_GetOffsetMm(void);

/**
  * @brief  设置单次测距的时间预算
  * @param  us 微秒。默认 33000（33ms），ST 的推荐值。
  *
  * @note   预算越大精度越高、抗噪越好，但出数越慢：
  *             20000us → 约 20ms 一帧，50Hz 左右，适合连续跟踪
  *             33000us → 默认，精度和速度折中
  *             200000us → 高精度长距离，200ms 一帧
  *         必须在初始化成功之后调用，内部会重算各阶段超时。
  *         本函数同时会更新 PollMeasDone() 用的等待时间。
  */
void VL53L0X_SetTimingBudgetUs(uint32_t us);

/**
  * @brief  读回当前 timing budget，单位 us
  */
uint32_t VL53L0X_GetTimingBudgetUs(void);

/* ---------------------------------------------------------------------------
 * 逃生口
 * ------------------------------------------------------------------------- */

/**
  * @brief  拿到内部设备句柄，可以直接调官方 API 里任意函数
  * @retval 设备句柄指针；初始化之前不要用
  *
  * @note   比如要做串扰校准、读 SPAD 数量、改测距模式，就靠它：
  *             VL53L0X_PerformXTalkCalibration(VL53L0X_GetDevice(), 100);
  *         注意这些函数多数是阻塞的，别在控制环里调。
  */
VL53L0X_DEV VL53L0X_GetDevice(void);

/* 底层用：把 I2C 句柄交给 vl53l0x_i2c_platform.c，一般不需要直接调 */
void VL53L0X_I2C_Bind(I2C_HandleTypeDef *hi2c);

#endif /* __VL53L0X_H */
