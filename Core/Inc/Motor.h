#ifndef __MOTOR_H
#define __MOTOR_H

#include "main.h"

/* ===========================================================================
 * 直流减速电机 + TB6612 驱动层
 *
 * 硬件接线（按已打板的原理图，不能改）：
 *
 *   TB6612 脚 10  PWMB  --- PA8  (TIM1_CH1，20kHz)
 *   TB6612 脚 12  BIN1  --- PB14 (推挽输出)
 *   TB6612 脚 11  BIN2  --- PB15 (推挽输出)
 *   TB6612 脚 13  STBY  --- +5V  （硬件常使能，软件关不掉）
 *   TB6612 脚 6/7 BO2/BO1 --- 电机
 *
 *   编码器 A --- PB6 (TIM4_CH1)
 *   编码器 B --- PB7 (TIM4_CH2)   PB6/PB7 是 5V 耐受(FT)引脚，5V 编码器直连安全
 *
 * 注意 STBY 硬接 5V：没有软件急停能力。软件只能通过 Motor_SetPower(0)
 * 或 Motor_Brake() 让电机停下，无法关断整片 TB6612。调试时若电源水管乱摆，
 * 只能断电。
 *
 * ---------------------------------------------------------------------------
 * 方向真值表（TB6612 数据手册）
 * ---------------------------------------------------------------------------
 *   BIN1  BIN2  PWMB     输出
 *    1     0    PWM      正转，速度 = 占空比
 *    0     1    PWM      反转，速度 = 占空比
 *    0     0    ×        滑行（高阻，自由停）
 *    1     1    ×        刹车（短接绕组，快速停）
 *
 * ---------------------------------------------------------------------------
 * 为什么直接用编码器计数当控制量
 * ---------------------------------------------------------------------------
 * 曲柄连杆的具体形式不影响软件：在可用工作区间内，编码器计数和水管倾角
 * 是单调一一对应的。所以 PID 直接在编码器域里跑，不需要做
 * 「曲柄转角 → 管子角度」的运动学反解，少一层模型误差。
 *
 * 如果实测发现方向反了，把 MOTOR_INVERT 改成 1 即可，不用改接线。
 * =========================================================================== */

/* ---------------------------------------------------------------------------
 * 引脚
 * ------------------------------------------------------------------------- */
#define MOTOR_BIN1_PORT         GPIOB
#define MOTOR_BIN1_PIN          GPIO_PIN_14
#define MOTOR_BIN2_PORT         GPIOB
#define MOTOR_BIN2_PIN          GPIO_PIN_15

/* TIM1 自动重装值，和 CubeMX 里 htim1.Init.Period 保持一致。
 * 72MHz / (0+1) / (3599+1) = 20kHz */
#define MOTOR_PWM_PERIOD        3599U

/* 对外功率量程：传 -1000 ~ +1000，符号表示方向 */
#define MOTOR_POWER_MAX         1000

/* 方向取反开关：装好后发现正转指令让球往反方向跑，就把这个改成 1 */
#ifndef MOTOR_INVERT
#define MOTOR_INVERT            0
#endif

/* ---------------------------------------------------------------------------
 * 接口
 * ------------------------------------------------------------------------- */

/**
  * @brief  初始化电机 PWM 与编码器
  * @note   必须在 MX_TIM1_Init() 和 MX_TIM4_Init() 之后调用（也就是 main 的
  *         USER CODE 2 里）。内部会启动 PWM 输出和编码器计数，并把编码器清零。
  *         初始化后电机处于滑行停止状态。
  */
void Motor_Init(void);

/**
  * @brief  设置电机功率
  * @param  power -1000 ~ +1000。正负表示方向，绝对值表示占空比。
  *                传 0 等于滑行停止。
  *
  * @note   立即返回，不阻塞。内部的饱和处理会先把超范围的值截断。
  */
void Motor_SetPower(int16_t power);

/**
  * @brief  滑行停止（高阻，电机自由转）
  */
void Motor_Stop(void);

/**
  * @brief  刹车停止（短接绕组，快速停住）
  */
void Motor_Brake(void);

/**
  * @brief  读编码器当前计数
  * @retval int16_t，范围 -32768 ~ +32767，超过会回绕
  */
int16_t Motor_GetEncoder(void);

/**
  * @brief  读编码器自上次调用以来的增量
  * @retval int16_t，正负表示转动方向
  *
  * @note   做速度估计时按固定周期调用它，差分值除以周期就是转速。
  *         内部自动处理 16 位计数器回绕。
  */
int16_t Motor_GetEncoderDelta(void);

/**
  * @brief  把编码器计数清零（当前位置当作零点）
  */
void Motor_ResetEncoder(void);

#endif /* __MOTOR_H */
